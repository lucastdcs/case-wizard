// Texto de tela no idioma da interface; chave sem tradução cai no PT (a base do
// produto), nunca em branco. Mapa por idioma, nunca ternário de dois idiomas.
export function ntt(key, ...args) {
    const dict = NOTE_TABLE_DICT[getLanguage()] || NOTE_TABLE_DICT.pt;
    const v = dict[key] !== undefined ? dict[key] : NOTE_TABLE_DICT.pt[key];
    if (typeof v === "function") return v(...args);
    return v === undefined ? key : v;
}
