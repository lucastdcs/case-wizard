// scripts/build-precall-standalone.mjs
//
// Build avulso do Pre-call Checklist (ADR-0020): um arquivo só, com a raspagem e
// o formulário, para entregar a quem não usa o app completo. Duas variantes:
//
//   padrão  a interface segue o idioma do navegador (pt, es ou en; PT se outro)
//   -en     100% inglês, na tela E no arquivo: sem texto em português ou espanhol
//           em lugar nenhum (dicionários, catálogo, rótulos de CRM, comentários,
//           console), interface fixa em EN e rodapé da nota em inglês
//
// Saída em dist/, por variante:
//   precall-standalone[-en].js    padrão: legível, para ler e para colar no console;
//                                 -en: o mesmo código minificado, sem comentários
//   precall-bookmarklet[-en].txt  minificado, numa linha `javascript:...`, para
//                                 colar como URL de um favorito
//
// Uso: npm run build:precall

import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ROTULOS_EN } from './precall-standalone-en-labels.mjs';

const raiz = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const saida = resolve(raiz, 'dist');

// O data-service tem efeito colateral no topo (um console.log) e carrega os IDs
// de implantação do Apps Script, então o esbuild não o poda mesmo sem uso — e o
// page-data importa dele. O Pre-call não fala com o backend: o arquivo que sai
// daqui não pode levar o endereço dele nem fazer chamada nenhuma. Se um dia o
// grafo do Pre-call passar a importar outro export, o build falha em vez de
// seguir com um undefined.
const semBackend = {
    name: 'sem-backend',
    setup(b) {
        b.onResolve({ filter: /data-service\.js$/ }, () => ({ path: 'data-service', namespace: 'sem-backend' }));
        b.onLoad({ filter: /.*/, namespace: 'sem-backend' }, () => ({
            contents: 'export const fetchUserProfile = async () => null;',
            loader: 'js',
        }));
    },
};

// Variante em inglês. O que ela corta vem de duas fontes, e nenhuma é "lembrar":
//
//   - GERADO a partir do código real (dicionário do Pre-call só com `en`, catálogo
//     de tasks só com os nomes, que é o único campo que o Pre-call lê): conteúdo
//     novo na produção entra sozinho;
//   - TROCADO com asserção (rodapé, aviso de falha ao copiar, dicionário do
//     cabeçalho, rótulos do CRM): se o trecho de produção mudar, o build falha em
//     vez de entregar o português.
//
// O i18n.js vira um módulo de idioma fixo `en` (src/precall-standalone-i18n-en.js).
const carregarReal = (rel) => import(pathToFileURL(resolve(raiz, rel)).href);
const { PRECALL_I18N } = await carregarReal('src/modules/notes/precall/precall-i18n.js');
const { TASKS_DB } = await carregarReal('src/modules/notes/data/notes-data.js');

// Troca exatamente 1 trecho; qualquer outra contagem derruba o build.
function trocar(fonte, arquivo, de, para) {
    const achados = typeof de === 'string' ? fonte.split(de).length - 1 : (fonte.match(new RegExp(de.source, 'g')) || []).length;
    if (achados !== 1) throw new Error(`${arquivo}: o build em inglês esperava 1 trecho para trocar e achou ${achados}: ${de}`);
    return fonte.replace(de, () => para);
}

const TROCAS = [
    { arquivo: 'precall-data.js', aplicar: (f, a) => trocar(f, a, "FOOTER = 'Gerado pelo Cases Wizard'", "FOOTER = 'Generated by Cases Wizard'") },
    {
        arquivo: 'notes-bridge.js',
        aplicar: (f, a) => trocar(
            trocar(f, a, `const COPY_ERROR_TOAST = { pt: "Falha ao copiar", es: "Error al copiar", en: "Failed to copy" };`, `const COPY_ERROR_TOAST = { en: "Copy failed" };`),
            a, 'COPY_ERROR_TOAST[getLanguage()] || COPY_ERROR_TOAST.pt', 'COPY_ERROR_TOAST.en'),
    },
    {
        arquivo: 'header-factory.js',
        aplicar: (f, a) => trocar(
            trocar(f, a, /\n    pt: \{[\s\S]*?\n    \},\n    es: \{[\s\S]*?\n    \},/, ''),
            a, 'HEADER_DICT.pt[key]', 'HEADER_DICT.en[key]'),
    },
    {
        arquivo: 'crm-labels.js',
        aplicar: (f, a) => {
            const bloco = /const ROTULOS = \{[\s\S]*?\n\};/;
            const literal = (f.match(bloco) || [''])[0].replace(/^const ROTULOS = /, '').replace(/;$/, '');
            const producao = new Function('return ' + literal)();
            const chavesProducao = Object.keys(producao).sort().join();
            if (chavesProducao !== Object.keys(ROTULOS_EN).sort().join()) {
                throw new Error(`${a}: os campos de ROTULOS mudaram; atualize ROTULOS_EN no build. Produção: ${chavesProducao}`);
            }
            for (const [campo, rotulos] of Object.entries(ROTULOS_EN)) {
                const faltam = rotulos.filter((r) => !producao[campo].includes(r));
                if (faltam.length) throw new Error(`${a}: ROTULOS.${campo} não tem mais ${JSON.stringify(faltam)}`);
            }
            return trocar(f, a, bloco, `const ROTULOS = ${JSON.stringify(ROTULOS_EN)};`);
        },
    },
];

const GERADOS = {
    'precall-i18n.js': `export const PRECALL_I18N = ${JSON.stringify({ en: PRECALL_I18N.en })};`,
    'notes-data.js': `export const TASKS_DB = ${JSON.stringify(Object.fromEntries(Object.entries(TASKS_DB).map(([slug, t]) => [slug, { name: t.name }])))};`,
};

const inglesFixo = {
    name: 'ingles-fixo',
    setup(b) {
        b.onResolve({ filter: /\/i18n\.js$/ }, () => ({ path: resolve(raiz, 'src/precall-standalone-i18n-en.js') }));
        b.onLoad({ filter: /\.js$/ }, async ({ path }) => {
            const nome = path.split('/').pop();
            if (GERADOS[nome] && path.includes('/src/modules/')) return { contents: GERADOS[nome], loader: 'js' };
            const troca = TROCAS.find((t) => t.arquivo === nome && path.includes('/src/modules/'));
            if (!troca) return undefined;
            return { contents: troca.aplicar(await readFile(path, 'utf8'), nome), loader: 'js' };
        });
    },
};

const BANNER_PT = `/*
 * Case Wizard — Pre-call Checklist (build avulso). Gerado por \`npm run build:precall\`; não edite.
 *
 * Como usar, na tela de um caso do CRM:
 *   - favorito: crie um favorito e cole o conteúdo de precall-bookmarklet.txt como URL; ou
 *   - console:  cole este arquivo inteiro no console do navegador e dê Enter.
 * O formulário abre já preenchido com o que a tela do caso informa. Fechou? Clique no
 * favorito de novo; com o formulário aberto, o clique relê o caso que está na tela.
 */
`;

const BANNER_EN = `/*
 * Case Wizard — Pre-call Checklist (standalone build, English only). Generated by \`npm run build:precall\`; do not edit.
 *
 * How to use, on a case screen in the CRM:
 *   - bookmark: create a bookmark and paste the contents of precall-bookmarklet-en.txt as its URL; or
 *   - console:  paste this whole file into the browser console and press Enter.
 * The form opens already filled with what the case screen shows. Closed it? Click the
 * bookmark again; with the form open, the click re-reads the case on screen.
 */
`;

const VARIANTES = [
    { sufixo: '', banner: BANNER_PT, plugins: [semBackend], ingles: false },
    { sufixo: '-en', banner: BANNER_EN, plugins: [semBackend, inglesFixo], ingles: true },
];

const comum = {
    entryPoints: [resolve(raiz, 'src/precall-standalone.js')],
    bundle: true,
    format: 'iife',
    write: false,
    logLevel: 'warning',
};

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
await mkdir(saida, { recursive: true });

for (const { sufixo, banner, plugins, ingles } of VARIANTES) {
    // Em inglês, nada de console (as mensagens de diagnóstico do código são em
    // português) nem de comentário. Os de JS o minificador já tira; os do CSS que o
    // código monta em template literals são TEXTO, ficariam no arquivo, então saem
    // daqui. `/* ... */` só sobra no bundle minificado dentro de string, e o smoke
    // confere que o desenho da tela não muda sem eles.
    const minificado = (await build({ ...comum, plugins, minify: true, ...(ingles && { drop: ['console'], legalComments: 'none' }) }))
        .outputFiles[0].text.trim();
    const codigo = ingles ? minificado.replace(/\/\*[\s\S]*?\*\//g, '') : minificado;

    // O .js em inglês é o mesmo código minificado: o legível carregaria os
    // comentários do código-fonte, que são em português.
    const arquivoJs = ingles
        ? banner + codigo + '\n'
        : (await build({ ...comum, plugins, banner: { js: banner } })).outputFiles[0].text;

    // Num favorito `javascript:` o navegador percent-decodifica a URL antes de
    // executar, descarta tudo depois de um `#` (fragmento) e apaga tabs e quebras
    // de linha. Sem escapar esses quatro, o código quebra sem erro nenhum: o CSS
    // tem `%` e `#` de sobra, e os template literals têm quebras de linha. Escapar
    // só eles (em vez de `encodeURIComponent`) mantém o favorito em ~77 KB, e não ~112.
    const bookmarklet = 'javascript:' + codigo
        .replace(/[%#\n\r\t]/g, (c) => '%' + c.charCodeAt(0).toString(16).toUpperCase().padStart(2, '0'));

    await writeFile(resolve(saida, `precall-standalone${sufixo}.js`), arquivoJs);
    await writeFile(resolve(saida, `precall-bookmarklet${sufixo}.txt`), bookmarklet + '\n');

    console.log(`dist/precall-standalone${sufixo}.js`.padEnd(38) + kb(arquivoJs.length));
    console.log(`dist/precall-bookmarklet${sufixo}.txt`.padEnd(38) + kb(bookmarklet.length));
}
