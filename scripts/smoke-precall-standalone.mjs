// --- Auditoria "100% inglês" do ARQUIVO (o `.txt` decodificado e o `.js`) ---
//
// Olhar a tela não basta: um arquivo que mostra tudo em inglês ainda pode CARREGAR
// os dicionários PT/ES, os rótulos de screenshot do catálogo, os rótulos de CRM
// traduzidos, comentários e mensagens de console em português — e é isso que quem
// abre o arquivo lê. A lista do que não pode aparecer vem do código de produção, não
// de uma lista escrita à mão: texto novo lá passa a ser proibido aqui sozinho.
const fonte = (rel) => readFileSync(resolve(raiz, rel), 'utf8');
const folhas = (v) => (typeof v === 'string' ? [v] : v && typeof v === 'object' ? Object.values(v).flatMap(folhas) : []);

const proibidosExatos = new Set([
    // dicionários PT/ES do Pre-call, e o texto de produção que o -en troca
    ...['pt', 'es'].flatMap((l) => Object.entries(PRECALL_I18N[l]).filter(([k, v]) => v !== PRECALL_I18N.en[k]).map(([, v]) => v)),
    'Gerado pelo Cases Wizard', 'Falha ao copiar', 'Error al copiar',
    // dicionários PT/ES do cabeçalho (não exportados: lidos do fonte)
    ...[...fonte('src/modules/shared/header-factory.js').matchAll(/^ {4}(?:pt|es): \{([\s\S]*?)\n {4}\}/gm)]
        .flatMap((m) => [...m[1].matchAll(/: "([^"]+)"/g)].map((x) => x[1])),
    // tudo do catálogo de tasks além do nome (rótulos de screenshot): o Pre-call só lê o nome
    ...Object.values(TASKS_DB).flatMap((t) => folhas(t.screenshots)),
    // rótulos de CRM que a produção tem e a lista em inglês não
    ...(() => {
        const bloco = fonte('src/modules/shared/crm-labels.js').match(/const ROTULOS = \{[\s\S]*?\n\};/)[0];
        const producao = new Function('return ' + bloco.replace(/^const ROTULOS = /, '').replace(/;$/, ''))();
        const em = new Set(Object.values(ROTULOS_EN).flat());
        return Object.values(producao).flat().filter((r) => !em.has(r));
    })(),
]);

// Palavras de PT/ES que não existem em inglês (sem "error" nem "cases", que existem):
// pega o texto SEM acento, que o teste de letras acentuadas não vê.
const VOCABULARIO_FORA_DO_INGLES = ('nao|para|uma|voce|seu|sua|dos|das|nos|nas|pelo|pela|estao|tambem|entao|ainda|quando|onde|porque|'
    + 'muito|falha|erro|fechar|voltar|versao|sobre|abrir|copiar|copiado|limpar|inserir|selecione|sim|campos|campo|preenchido|'
    + 'preencha|telefone|correo|electronico|pantalla|completado|llamada|tarefa|tarefas|tareas|agendamento|cita|caso|tela|nota|'
    + 'vendedor|vendas|ventas|prosseguir|continuar|inviavel|inviable|escopo|alcance|motivo|excecao|instrucoes|instrucciones|'
    + 'proximos|pasos|passos|conteudo|contenido|colar|pegar|manualmente|ligacao|nome|nombre|apellido|familia|horario|fuso|zona|'
    + 'roteamento|enrutamiento|idioma|linguagem|oferta|parceiro|socio|proveedor|produto|producto|programa|sitio|informacoes|'
    + 'informacion|adicional|numero|contato|contacto|acesso|acceso|criado|creado|gerado|generado|titulo|descricao|descripcion|'
    + 'ajuda|ayuda|aviso|obrigatorio|requerido|sucesso|exito|aguarde|espere|carregando|cargando|salvar|guardar|cancelar|'
    + 'excluir|eliminar|editar|buscar|procurar|filtrar|todos|todas|nenhum|ninguno|usuario|segmento|disponibilidade|'
    + 'disponibilidad|resumo|resumen|detalhes|detalles').split('|');
const REGEX_VOCABULARIO = new RegExp(`(?<![A-Za-z0-9_$.-])(${VOCABULARIO_FORA_DO_INGLES.join('|')})(?![A-Za-z0-9_$-])`, 'gi');

// Por palavra inteira: "site" (rótulo PT do CRM) não pode reprovar o "website" em inglês.
const escaparRegex = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const aparece = (texto, t) => new RegExp(`(?<![A-Za-z0-9])${escaparRegex(t)}(?![A-Za-z0-9])`).test(texto);

function auditarIngles(texto) {
    return {
        letrasAcentuadas: (texto.match(/\\x[C-F][0-9A-Fa-f]|\\u00[C-F][0-9A-Fa-f]|[\u00C0-\u00FF\u00BF\u00A1]/g) || []).length,
        comentarios: (texto.match(/\/\*/g) || []).length,
        console: (texto.match(/console\./g) || []).length,
        textosProibidos: [...proibidosExatos].filter((t) => aparece(texto, t)),
        vocabulario: [...new Set([...texto.matchAll(REGEX_VOCABULARIO)].map((m) => m[0].toLowerCase()))],
    };
}
const LIMPO = { letrasAcentuadas: 0, comentarios: 0, console: 0, textosProibidos: [], vocabulario: [] };

